"""Turn report/amd_summary.csv (from analyze_amd.py) into report/numbers.tex.

Run from the project root, after analyze_amd.py:
    python src/make_report_numbers.py
Then compile report/report.tex. Every number in the report comes from this file.
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
s = pd.read_csv(ROOT / "report" / "amd_summary.csv", index_col=0)["value"]


def num(key, nd=3):
    return f"{float(s[key]):.{nd}f}"


def pval(key):
    p = float(s[key])
    return "$<0.001$" if p < 0.001 else f"{p:.3f}"


macros = {
    "nDays": str(int(float(s["n_days"]))),
    "dataStart": str(s["start"]),
    "dataEnd": str(s["end"]),
    "sigmahat": num("sigma_hat"), "sesigma": num("se_sigma"),
    "muhat": num("mu_hat"), "semu": num("se_mu"),
    "skewv": num("skew"), "exkurt": num("excess_kurtosis"),
    "jbp": pval("jarque_bera_p"), "shapirop": pval("shapiro_p"),
    "pctthree": num("pct_days_beyond_3sigma", 2),
    "acf": num("abs_return_autocorr_lag1"),
}
# Option-snapshot numbers exist only if collect_amd.py found usable quotes
for mac, key, nd in [("nquotes", "n_quotes_used", 0), ("sigmahist", "sigma_hist_60d", 3),
                     ("meaniv", "mean_implied_vol", 3), ("atmiv", "atm_implied_vol", 3),
                     ("rmse", "rmse_price", 2), ("relerr", "mean_rel_error", 3)]:
    if key in s.index:
        macros[mac] = num(key, nd)
if "snapshot_date" in s.index:
    macros["snapdate"] = str(s["snapshot_date"])

out = ROOT / "report" / "numbers.tex"
out.write_text("% Auto-generated by src/make_report_numbers.py. Do not edit by hand.\n" +
               "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))
print(f"Wrote {out} with {len(macros)} values")